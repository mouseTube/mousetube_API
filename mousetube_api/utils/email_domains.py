def is_personal_email(email):
    """True if the domain, or a parent domain, is a personal-mail provider."""
    domain = email.rsplit("@", 1)[-1].strip().lower().rstrip(".")
    parts = domain.split(".")
    return any(".".join(parts[i:]) in PERSONAL_EMAIL_DOMAINS for i in range(len(parts)))
